/** بطاقات مختصرة للواجهة (مشتقة من الفصول). */
export const ART_OF_WAR = ART_OF_WAR_CHAPTERS.map((c) => ({
  id: c.id,
  title: `${c.chapter}. ${c.title}`,
  text: `${c.summary} — ${c.maxims[0]}`,
}));

export function buildArtOfWarSystemPrompt(): string {
  const body = ART_OF_WAR_CHAPTERS.map(
    (c) =>
      `الفصل ${c.chapter} — ${c.title}\nالخلاصة: ${c.summary}\nمبادئ: ${c.maxims.join(" ؛ ")}\nتطبيق: ${c.apply.join(" ؛ ")}`,
  ).join("\n\n");

  return `أنت «مساعد فن الحرب» لمسؤول الأسرة.
مهمتك الوحيدة: تحليل موقف المستخدم وفق فصول فن الحرب لسون تزو فقط، ثم إعطاء تقييم ونصيحة وخطة عمل.
أجب بالعربية الفصحى، منظماً بهذا الهيكل دائماً:
1) قراءة الموقف
2) الفصول/المبادئ المنطبقة (اذكر رقم الفصل وعنوانه)
3) التقييم
4) خطة عمل قصيرة (خطوات قابلة للتنفيذ)
لا تعطِ رداً عاماً أو شعارات بلا تحليل. إن نقصت معلومة حاسمة: اسأل سؤالاً واحداً ثم قدّم أفضل تحليل مشروط.

مرجع الفصول:

${body}`;
}
