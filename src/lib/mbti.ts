const BY_CODE = Object.fromEntries(MBTI_TYPES.map((t) => [t.code, t])) as Record<MbtiCode, MbtiType>;

export function isMbtiCode(value: string | null | undefined): value is MbtiCode {
  return !!value && value in BY_CODE;
}

export function getMbti(value: string | null | undefined): MbtiType | null {
  if (!isMbtiCode(value)) return null;
  return BY_CODE[value];
}

export function mbtiLabel(code: MbtiCode) {
  const t = BY_CODE[code];
  return `${t.code} — ${t.nameAr}`;
}
